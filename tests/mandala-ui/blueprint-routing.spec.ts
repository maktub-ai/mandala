import {expect} from '@playwright/test';
import {test} from '../e2e/helpers/isolated-authority';

test('new task waits for the human to amend the module and keeps the final choice',async({page,isolatedAuthority:{request,baseURL}},info)=>{
 test.setTimeout(60000);
 const {directory}=await(await request.post('/__test__/execution-directory')).json();
 const {config,revision}=await(await request.get('/api/config')).json(),projectId='route-editor';
 const project={id:projectId,name:'图形编辑器',cwd:directory,agentIds:[],skills:[],resources:[],mcp:[]};
 expect((await request.put('/api/config',{data:{revision,config:{...config,projects:[...config.projects,project]}}})).ok()).toBe(true);
 const path='/api/projects/'+projectId+'/blueprint';
 expect((await request.post(path,{data:{action:'enable'}})).ok()).toBe(true);
 const draft=await(await request.post(path,{data:{action:'draft'}})).json();
 expect((await request.post(path,{data:{action:'confirm',draftId:draft.draftId,modules:['画布','导出']}})).ok()).toBe(true);
 await page.addInitScript(()=>localStorage.setItem('mana-language','zh-CN'));
 await page.goto(baseURL+'/tasks?project='+projectId+'&action=create');
 await page.getByRole('button',{name:'手动填写',exact:true}).click();
 const form=page.getByRole('form',{name:'新建任务',exact:true});
 await form.getByRole('textbox',{name:'任务标题',exact:true}).fill('更新画布导出');
 const waiting=page.waitForResponse(r=>r.url().endsWith('/route-preview'));
 await form.getByRole('button',{name:'创建任务',exact:true}).click();
 const review=await(await waiting).json();
 const card=page.getByRole('region',{name:'蓝图分派建议'});
 await expect(card).toBeVisible();
 const list=async()=>await(await request.get('/api/v2/tasks?projectId='+projectId)).json();
 expect(await list()).toHaveLength(0);
 await card.getByRole('combobox',{name:'建议模块'}).click();await page.getByRole('option',{name:'导出',exact:true}).click();
 await page.screenshot({path:info.outputPath('blueprint-route.png'),animations:'disabled'});
 await card.getByRole('button',{name:'确认并创建任务'}).click();
 await expect(page).toHaveURL(/\/tasks\/[a-z0-9-]+$/);
 const tasks=await list();expect(tasks).toHaveLength(1);expect(tasks[0].moduleRef).toEqual({projectId,lane:'导出'});
 const audit=await(await request.get('/api/v2/tasks/route-reviews/'+review.id)).json();
 expect(audit).toMatchObject({status:'confirmed',matched:false,selection:{projectId,lane:'导出'}});
 await page.goto(baseURL+'/tasks/'+tasks[0].id+'?action=edit');
 const edit=page.getByRole('form',{name:'编辑任务',exact:true});
 await edit.getByText('涉及的项目',{exact:true}).click();
 await edit.getByRole('checkbox',{name:'从执行会话自动归属'}).uncheck();
 await edit.getByRole('checkbox',{name:'图形编辑器'}).uncheck();
 await edit.getByRole('button',{name:'保存任务',exact:true}).click();
 await expect.poll(async()=>{const detail=await(await request.get('/api/v2/tasks/'+tasks[0].id)).json();return [detail.task.projectIdsMode,detail.task.projectIds];}).toEqual(['manual',[]]);
 await page.goto(baseURL+'/library?project='+projectId+'&tab=plan');await expect(page).toHaveURL(baseURL+'/projects/'+projectId+'/overview');
});
