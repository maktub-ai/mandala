import {DomainError} from '../shared/workspace-contracts';
import {afterEach,expect,it} from 'vitest';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openStore} from '../server/store';
import {createTasks} from '../server/tasks';
import {conversationResults} from '../server/conversation-results';
const clean:(()=>void)[]=[];afterEach(()=>clean.splice(0).forEach(fn=>fn()));
it('returns durable receipt results with the exact execution, never unrelated or unauthorized results',()=>{
 const home=mkdtempSync(join(tmpdir(),'conversation-results-')),store=openStore(home),tasks=createTasks(store),p={userId:store.ownerUserId};
 clean.push(()=>{store.close();rmSync(home,{recursive:true,force:true});});
 const destination=store.createConversation({projectId:'',agentId:'main',cli:'codex',model:null});
 const execution=store.createConversation({projectId:'',agentId:'worker',cli:'codex',model:null});
 const task=tasks.createTask(p,{goal:'Inspect differences',assigneeAgentId:'worker',originConversationId:destination.id},'result-task');
 const membership=tasks.createExecution(p,task.id,{conversationId:execution.id,agentId:'worker',projectId:null,request:'Inspect differences'},'execute');
 const at='2026-10-31T01:00:00Z';
 store.database.prepare("INSERT INTO task_runs(id,task_id,execution_id,attempt,state,routing,summary,created_at) VALUES (?,?,?,1,'succeeded',?,?,?)").run('exact-run',task.id,membership.id,JSON.stringify({executionConversationId:execution.id,destinationConversationId:destination.id,mode:'dedicated'}),'Two differences.',at);
 store.database.prepare("INSERT INTO task_receipts(id,task_id,source_run_id,destination_conversation_id,execution_id,policy,delivery_state,summary,artifact_versions,created_at) VALUES (?,?,?,?,?,'notify','consumed',?,'[]',?)").run('receipt',task.id,'exact-run',destination.id,membership.id,'Two differences.',at);
 const result=conversationResults(store,tasks,p,destination.id,()=>{});
 expect(result).toMatchObject([{id:'receipt',runId:'exact-run',conversationId:execution.id,agentId:'worker',title:'Inspect differences',summary:'Two differences.',state:'succeeded',createdAt:at}]);
 expect(result[0]).toMatchObject({taskState:'todo',completion:null});
 expect(conversationResults(store,tasks,p,execution.id,()=>{})).toEqual([]);
 expect(()=>conversationResults(store,tasks,{userId:'other'},destination.id,()=>{})).toThrow();
 expect(conversationResults(store,tasks,p,destination.id,()=>{})).toEqual(result);
 store.renameConversation(execution.id,'Billing collection check');
 expect(conversationResults(store,tasks,p,destination.id,()=>{})[0].title).toBe('Billing collection check');
 store.renameConversation(execution.id,'Renamed collection check');
 expect(conversationResults(store,tasks,p,destination.id,()=>{})[0].title).toBe('Renamed collection check');
 expect(conversationResults(store,tasks,p,destination.id,chat=>{if(chat===execution.id)throw new DomainError('forbidden',403,'Source access revoked');})).toEqual([]);
 const completed=tasks.moveTask(p,task.id,task.revision,'completed',null,'complete-task');
 expect(conversationResults(store,tasks,p,destination.id,()=>{})[0]).toMatchObject({taskState:'completed',completion:{completedBy:'user'}});
 tasks.moveTask(p,task.id,completed.revision,'todo',null,'reopen-task');
 expect(conversationResults(store,tasks,p,destination.id,()=>{})[0]).toMatchObject({taskState:'todo',completion:null});
});
