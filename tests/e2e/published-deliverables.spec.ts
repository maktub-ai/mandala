import {expect,test} from '@playwright/test';
import {openChatContext} from './helpers/navigation';

for(const language of ['zh-CN','en'])test('published filename opens its pinned version in the sidebar with local app actions in '+language,async({page,request})=>{
 const en=language==='en';await page.addInitScript(lang=>localStorage.setItem('mana-language',lang),language);
 const {config,revision}=await(await request.get('/api/config')).json(),agentId='delivery-'+crypto.randomUUID();
 expect((await request.put('/api/config',{data:{revision,config:{...config,agents:[...config.agents,{id:agentId,name:'ERP 数据开发',instructions:'Export assets',defaultCli:'codex',models:{},skills:[],mcp:[]}]}}})).ok()).toBe(true);
 const chat=await(await request.post('/api/conversations',{data:{projectId:'',agentId,cwd:'/tmp',cli:'codex'}})).json();
 const seeded=await request.post('/__test__/published-deliverable',{data:{conversationId:chat.id}});expect(seeded.ok(),await seeded.text()).toBe(true);
 const output=await seeded.json(),base='/api/v2/assets/'+output.asset.id+'/versions/'+output.version.id+'/files/0';
 const newerStage=await(await request.post('/api/v2/assets/uploads?name='+output.name,{data:'Newer workbook must not replace the delivered version'})).json();
 expect((await request.post('/api/v2/assets/'+output.asset.id+'/versions',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{expectedHeadVersionId:output.version.id,submissionId:newerStage.submissionId,provenance:{sourceVersions:[]}}})).ok()).toBe(true);
 const actions:string[]=[];
 await page.route('**'+base+'/open',async route=>{actions.push(route.request().postDataJSON().action);await route.fulfill({json:{ok:true}});});
 await page.goto('/?conversation='+chat.id);
 const draft=page.getByRole('textbox',{name:en?'Message':'消息',exact:true});await draft.fill('保留当前讨论');
 const link=page.locator('.message.text').getByRole('link',{name:output.name,exact:true});await expect(link).toBeVisible();
 await link.evaluate(el=>el.setAttribute('data-original-link','true'));
 await draft.fill('继续讨论交付物');await expect(link).toHaveAttribute('data-original-link','true');
 await request.post('/api/conversations/'+chat.id+'/messages',{data:{text:'hold'}});
 await expect(page.getByText('Fixture reply: hold',{exact:true})).toBeVisible();
 await request.post('/api/conversations/'+chat.id+'/stop',{data:{}});
 await expect(link).toHaveAttribute('data-original-link','true');
 await draft.fill('保留当前讨论');await link.click();
 const panel=page.locator('#chat-environment-panel');
 await expect(panel.getByRole('heading',{name:output.name,exact:true})).toBeVisible();
 await expect(panel).toContainText(en?'This format':'暂不支持此格式');
 await panel.getByRole('button',{name:en?'Open in default app':'用默认应用打开',exact:true}).click();
 await expect(panel.getByRole('status')).toContainText(en?'Opened local copy':'已打开本地副本');
 await panel.getByRole('button',{name:en?'Show in folder':'在文件夹中显示',exact:true}).click();expect(actions).toEqual(['open','reveal']);
 const download=await request.get(base);expect(download.ok()).toBe(true);expect(await download.text()).toBe('Synthetic workbook bytes');
 await panel.getByRole('button',{name:en?'Collapse right sidebar':'收起右侧栏',exact:true}).press('Escape');await expect(draft).toHaveValue('保留当前讨论');
 await page.getByRole('button',{name:en?'Expand right sidebar':'展开右侧栏',exact:true}).click();
 await panel.getByRole('button',{name:en?'Close preview':'关闭预览',exact:true}).click();
 await (await openChatContext(page)).getByRole('button',{name:/近30天阅读书目清单/}).click();
 await expect(panel.getByRole('button',{name:en?'Open in default app':'用默认应用打开',exact:true})).toBeVisible();
 await page.unroute('**'+base+'/open');
 await page.route('**'+base+'/open',route=>route.fulfill({status:503,json:{error:'无法打开本地文件，请下载后使用本机应用打开。'}}));
 await panel.getByRole('button',{name:en?'Open in default app':'用默认应用打开',exact:true}).click();await expect(panel.getByRole('alert')).toBeVisible();
 await page.unroute('**'+base+'/open');
 await page.route('**/api/v2/assets/'+output.asset.id,route=>route.fulfill({status:403,json:{error:'forbidden'}}));
 await panel.getByRole('button',{name:en?'Close preview':'关闭预览',exact:true}).click();await (await openChatContext(page)).getByRole('button',{name:/近30天阅读书目清单/}).click();
 await expect(panel.getByRole('alert')).toBeVisible();await expect(panel.getByRole('button',{name:en?'Open in default app':'用默认应用打开',exact:true})).toHaveCount(0);
});
