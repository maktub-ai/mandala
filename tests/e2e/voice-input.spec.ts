import {test,expect} from '@playwright/test';
import {chooseOption} from './helpers/select';
test.use({launchOptions:{args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']}});
test('voice is opt-in and saves a key without exposing it on reload',async({page,request},testInfo)=>{
 await page.goto('/settings/general');
 const section=page.getByRole('region',{name:'语音输入',exact:true});
 await expect(section.getByRole('checkbox',{name:'启用语音输入'})).not.toBeChecked();
 await section.screenshot({path:testInfo.outputPath('voice-local-settings.png')});
 await section.getByRole('checkbox',{name:'启用语音输入'}).check();
 await chooseOption(page,'识别方式','openai');
 await section.getByLabel('OpenAI API Key',{exact:true}).fill('synthetic-test-key');
 await section.getByRole('button',{name:'保存语音设置',exact:true}).click();
 await expect(section.getByText('已保存', {exact:true})).toBeVisible();
 expect(JSON.stringify(await (await request.get('/api/voice')).json())).not.toContain('synthetic-test-key');
 await page.reload();
 await expect(section.getByRole('checkbox',{name:'启用语音输入'})).toBeChecked();
 await expect(section.getByLabel('OpenAI API Key',{exact:true})).toHaveValue('');
 await page.setViewportSize({width:390,height:844});
 await expect(section).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await section.screenshot({path:testInfo.outputPath('voice-cloud-settings-mobile.png')});
});
test('dictation appends a draft and never sends it; cancelling keeps the existing draft',async({page,request})=>{
 await request.put('/api/voice',{data:{enabled:true,provider:'openai',apiKey:'synthetic-test-key'}});
 let uploads=0,sends=0;
 await page.route('**/api/voice/transcribe',async route=>{uploads++;expect(route.request().postDataBuffer()?.subarray(0,4).toString()).toBe('RIFF');await route.fulfill({json:{text:'追加语音内容'}});});
 page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/queue'))sends++;});
 const {config,revision}=await (await request.get('/api/config')).json();
 await request.put('/api/config',{data:{revision,config:{...config,agents:[...config.agents,{id:'voice-writer',name:'Voice writer',instructions:'Synthetic voice fixture',defaultCli:'codex',models:{},mcp:[],skills:[]}]}}});
 await page.goto('/?agent=voice-writer');
 const input=page.getByLabel('消息',{exact:true});await input.fill('原有草稿');
 await page.getByRole('button',{name:'语音输入',exact:true}).click();
 await expect(page.getByRole('button',{name:'停止录音',exact:true})).toBeVisible();
 await page.waitForTimeout(1100);
 await page.getByRole('button',{name:'停止录音',exact:true}).click();
 await expect(input).toHaveValue('原有草稿\n追加语音内容');expect(uploads).toBe(1);expect(sends).toBe(0);
 await page.getByRole('button',{name:'语音输入',exact:true}).click();
 await expect(page.getByRole('button',{name:'停止录音',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'取消语音输入',exact:true}).click();
 await expect(input).toHaveValue('原有草稿\n追加语音内容');expect(uploads).toBe(1);
 await page.unroute('**/api/voice/transcribe');
 await page.route('**/api/voice/transcribe',route=>route.fulfill({status:502,json:{error:'Provider unavailable'}}));
 await page.getByRole('button',{name:'语音输入',exact:true}).click();
 await page.waitForTimeout(1100);await page.getByRole('button',{name:'停止录音',exact:true}).click();
 await expect(page.getByRole('alert').filter({hasText:'Provider unavailable'})).toBeVisible();
 await expect(input).toHaveValue('原有草稿\n追加语音内容');
 await page.unroute('**/api/voice/transcribe');
 let release!:()=>void;const held=new Promise<void>(resolve=>{release=resolve;});let started=false;
 await page.route('**/api/voice/transcribe',async route=>{started=true;await held;await route.fulfill({json:{text:'迟到的结果'}}).catch(()=>{});});
 await page.getByRole('button',{name:'语音输入',exact:true}).click();
 await page.waitForTimeout(1100);await page.getByRole('button',{name:'停止录音',exact:true}).click();
 await expect.poll(()=>started).toBe(true);
 await page.getByRole('button',{name:'取消语音输入',exact:true}).click();release();
 await expect(page.getByRole('button',{name:'语音输入',exact:true})).toBeEnabled();
 await expect(input).toHaveValue('原有草稿\n追加语音内容');expect(sends).toBe(0);
 await page.getByRole('button',{name:'语音输入',exact:true}).click();
 await expect(page.getByRole('button',{name:'停止录音',exact:true})).toBeVisible();
 await page.goto('/settings/general');await page.goto('/?agent=voice-writer');
 await expect(page.getByRole('button',{name:'语音输入',exact:true})).toBeEnabled();
 await expect(input).not.toHaveValue(/迟到的结果/);expect(sends).toBe(0);
});
