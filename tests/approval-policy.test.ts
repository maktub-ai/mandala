import {afterEach,expect,it} from 'vitest';
import {mkdtempSync,mkdirSync,realpathSync,rmSync,symlinkSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,sep} from 'node:path';
import {canApproveAcpLocally} from '../server/approval-policy';
const homes:string[]=[];
afterEach(()=>homes.splice(0).forEach(h=>rmSync(h,{recursive:true,force:true})));
it('approves structured local read/edit requests only; commands and missing scope still ask',()=>{
 const cwd=mkdtempSync(join(tmpdir(),'approval-policy-'));homes.push(cwd);const path=join(cwd,'file.txt');writeFileSync(path,'sample');
 const tool=(kind:string,file=path)=>({kind,rawInput:{path:file},locations:[{path:file}]});
 const outside=mkdtempSync(join(tmpdir(),'approval-outside-'));homes.push(outside);
 const outsideFile=join(outside,'synthetic.txt');writeFileSync(outsideFile,'outside fixture');
 const linkType=process.platform==='win32'?'junction':'dir';
 expect(canApproveAcpLocally(tool('read'),cwd)).toBe(true);expect(canApproveAcpLocally(tool('edit'),cwd)).toBe(true);
 for(const input of [tool('execute'),tool('delete'),tool('read',outsideFile),{kind:'edit',rawInput:{path},locations:[]},{kind:'read'},tool('other')])expect(canApproveAcpLocally(input,cwd)).toBe(false);
 const link=join(cwd,'link');symlinkSync(outside,link,linkType);
 expect(realpathSync(link)).toBe(realpathSync(outside));
 expect(canApproveAcpLocally(tool('edit',join(cwd,'link','new.txt')),cwd)).toBe(false);
 const child=join(outside,'child'),escape=join(cwd,'escape');mkdirSync(child);symlinkSync(child,escape,linkType);
 expect(canApproveAcpLocally(tool('read',escape+sep+'..'+sep+'synthetic.txt'),cwd)).toBe(false);
 mkdirSync(join(cwd,'new'));expect(canApproveAcpLocally(tool('edit',join(cwd,'new','file.txt')),cwd)).toBe(true);
 expect(canApproveAcpLocally({...tool('edit'),rawInput:{path:outsideFile}},cwd)).toBe(false);
});
